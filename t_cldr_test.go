// Each language, each category, against CLDR's own sample counts.
func TestEveryLanguageAgainstCLDRSamples(t *testing.T) {
	for _, row := range cldrSamples {
		p := patternFor(row.lang)

		for _, count := range row.counts {
			op, isNumber := parseOperands(itoa(count))
			if !isNumber {
				t.Fatalf("%s: could not parse count %d", row.lang, count)
			}

			if got := p.fn(op); got != row.cat {
				t.Errorf("%s (pattern %s): count %d = `%s`, CLDR says `%s`",
					row.lang, p.name, count, got, row.cat)
			}
		}
	}
}

// Every registered language must appear in the sample table, so coverage
// cannot silently drop when a language is added.
func TestEveryRegisteredLanguageHasSamples(t *testing.T) {
	sampled := map[string]bool{}
	for _, row := range cldrSamples {
		sampled[row.lang] = true
	}

	for lang := range patternByLang {
		if !sampled[lang] {
			t.Errorf("language `%s` is registered but has no CLDR samples", lang)
		}
	}
}

// itoa keeps the sample table free of strconv noise at every call site.
func itoa(n int64) string {
	return strconv.FormatInt(n, 10)
}

// End-to-end coverage for every registered language: build one mapping block
// per language holding all six forms, then check Get() returns the form the
// language's ruleset selects. Exercises the YAML parsing, the engine switch,
// the lookup, and the fallback -- not just the rule functions.
func TestEveryLanguageThroughGet(t *testing.T) {
	yaml := "x:\n"
	langs := make([]string, 0, len(patternByLang))
	for lang := range patternByLang {
		langs = append(langs, lang)
	}
	sort.Strings(langs)

	for _, lang := range langs {
		yaml += "  " + lang + ":\n"
		for _, cat := range []category{catZero, catOne, catTwo, catFew, catMany, catOther} {
			yaml += "    " + cat.String() + ": " + cat.String() + "\n"
		}
	}

	path := writeYAML(t, t.TempDir(), "all.yml", yaml)
	bla, err := Load(path)
	if err != nil {
		t.Fatal(err)
	}
	if bla.Errors != nil {
		t.Fatalf("fixture should validate clean: %v", bla.Errors)
	}

	for _, lang := range langs {
		p := patternFor(lang)

		for count := int64(0); count <= 130; count++ {
			op, isNumber := parseOperands(itoa(count))
			if !isNumber {
				t.Fatalf("%s: could not parse %d", lang, count)
			}

			want := p.fn(op).String()
			if got := bla.Get(lang, "x", count); got != want {
				t.Errorf("Get(%q, x, %d) = `%s`, want `%s` (pattern %s)", lang, count, got, want, p.name)
			}
		}
	}
}
